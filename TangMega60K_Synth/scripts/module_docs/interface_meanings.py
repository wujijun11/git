def describe(module, port):
    """每个端口必须有说明，无法覆盖时显式报错以便人工补齐。"""
    name = port["name"]
    if (module["name"], name) in SPECIFIC:
        return SPECIFIC[(module["name"], name)]
    if name in ALIASES:
        return COMMON[ALIASES[name]]
    if name in COMMON:
        return COMMON[name]
    if name == "current_expr_gain":
        return "交互层当前完整目标增益，Q1.11，2048=1倍；是否已在音源帧边界生效要看后续提交器。"
    if name == "current_expr_bend_cents":
        return "交互层当前完整目标弯音，单位音分；不是保证已经提交到音源的active_bend_cents。"
    if name == "current_expr_vibrato_cents":
        return "交互层当前完整目标颤音深度，单位音分；后续仍须通过表情握手和帧边界提交。"
    if name in {"left", "right"}:
        return f"本次声部/通道计算的{'左' if name == 'left' else '右'}路有符号振幅，valid有效时读取。"
    if name in {"sample", "sample_in", "mode", "data"}:
        raise ValueError(f"需要模块专用解释：{module['name']}.{name}")
    for group in sorted(GROUPS, key=len, reverse=True):
        if not name.startswith(group + "_"):
            continue
        suffix = name[len(group) + 1:]
        label = GROUPS[group]
        if suffix == "valid":
            return f"{label}有效指示；标准流接口与同组ready在同一时钟边沿同时为1才接收。无ready的观察脉冲另见时序说明。"
        if suffix == "ready":
            return f"{label}接收许可；不是发送完成或全系统就绪。与同组valid同时为1才完成一次传输。"
        if suffix in FIELDS:
            return label + FIELDS[suffix]
    raise ValueError(f"未解释的端口：{module['name']}.{name}")
