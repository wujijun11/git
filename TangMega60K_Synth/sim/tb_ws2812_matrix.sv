module tb_ws2812_matrix;
    wire identity_done,serpentine_done,rotated_done;
    // Identity uses oversized raw brightness values to prove both channels
    // are independently limited. Other layouts use normal green32/blue16.
    ws2812_matrix_check identity(.done(identity_done));
    ws2812_matrix_check #(.LAYOUT(1),.GREEN_RAW(8'd32),.BLUE_RAW(8'd16),
        .EXPECTED_BLUE(8'd16),.PIXEL_KEY_MAP({
            5'd24,5'd23,5'd22,5'd21,5'd20,5'd15,5'd16,5'd17,5'd18,5'd19,
            5'd14,5'd13,5'd12,5'd11,5'd10,5'd5,5'd6,5'd7,5'd8,5'd9,
            5'd4,5'd3,5'd2,5'd1,5'd0})) serpentine(.done(serpentine_done));
    ws2812_matrix_check #(.LAYOUT(2),.GREEN_RAW(8'd32),.BLUE_RAW(8'd16),
        .EXPECTED_BLUE(8'd16),.PIXEL_KEY_MAP({
            5'd0,5'd1,5'd2,5'd3,5'd4,5'd9,5'd8,5'd7,5'd6,5'd5,
            5'd10,5'd11,5'd12,5'd13,5'd14,5'd19,5'd18,5'd17,5'd16,5'd15,
            5'd20,5'd21,5'd22,5'd23,5'd24})) rotated(.done(rotated_done));
    initial begin
        wait(identity_done && serpentine_done && rotated_done);
        $display("ALL WS2812 MATRIX TESTS PASSED");$finish;
    end
    initial begin #50000000;$fatal(1,"WS2812 matrix simulation watchdog");end
endmodule
